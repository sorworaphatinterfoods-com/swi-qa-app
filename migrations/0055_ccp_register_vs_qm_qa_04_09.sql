-- 0055_ccp_register_vs_qm_qa_04_09.sql
--
-- The CCP register is compared against the two HACCP documents that became
-- effective on 07/08/26 and now govern it:
--
--   QM-QA-04 Rev.05  การวิเคราะห์อันตรายและแผนควบคุมจุดวิกฤต
--   QM-QA-09 Rev.00  แผนภูมิกระบวนการผลิตและคำบรรยายขั้นตอน
--
-- Both cover the RTC (ดิบแช่เยือกแข็ง) stream only. Between them they declare
-- one CCP and — depending which one you read — two or three OPRPs. The register
-- in this system declares four CCPs and four OPRPs, in a different order, and
-- omits the two OPRPs that are the only ones with a written control plan.
--
-- What this migration does:
--
--   1. moves the RTC rows onto the approved 19-step flow, which corrects the
--      position of CCP 1;
--   2. adds the two RTC control points that exist in the approved plan and not
--      in the register, transcribed from QM-QA-04 Rev.05 ข้อ 4;
--   3. marks the Par-cooked and RTE rows as ร่าง, because both documents state
--      those groups have not been hazard-analysed;
--   4. records, on each affected row, where the register and the approved
--      documents still disagree — without resolving disagreements that are the
--      HACCP team's to resolve;
--   5. raises the six findings that survive as NCs.
--
-- Nothing is deleted. The Par-cooked and RTE rows were loaded deliberately and
-- stay where they are; they are labelled, not removed.

ALTER TABLE ccps ADD COLUMN notes TEXT;

-- ── 1. the position of CCP 1 ────────────────────────────────────────────────
-- This is the substantive error. The register runs the metal detector at step
-- 10, after the blast freezer (8) and after packaging (9). QM-QA-09 Rev.00
-- exists in part to fix exactly this: its revision note reads "แก้ไขตำแหน่ง
-- ขั้นตอนการตรวจจับโลหะให้อยู่ก่อนการบรรจุ ตามที่ได้รับการยืนยันจากหน้างานว่า
-- เป็นการตรวจสินค้าเปลือย". The approved order is skewering (12) → metal
-- detection (13) → packing (14, 15) → blast freezer (16).
--
-- It is not a cosmetic difference. Detecting through a printed bag and a
-- cardboard box is a different test from detecting naked product, and QM-QA-09
-- ข้อ 3 turns the position into an argument the factory has to be able to make:
-- packaging enters after the CCP, so nothing downstream catches it.
