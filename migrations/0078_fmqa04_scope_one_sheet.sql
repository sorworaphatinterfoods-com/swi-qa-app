-- Two things settled at once. The scope of FM-QA-04 is those checks and no
-- more, and the unit of the form is the shift's size-reduction run — all the
-- raw materials that went through it — not one material per sheet.
--
-- The three records for that day (IPI0054 สะโพกหมู, IPI0055 มันสันแข็ง,
-- IPI0056 อกไก่) stay three records. Nothing here merges them. What changed is
-- that the system can now print them as one form, materials in columns, with
-- each parameter and its limit written once instead of three times.

UPDATE haccp_documents SET
  notes = TRIM(COALESCE(notes,'') || ' | [17/08/26] QA ระบุขอบเขตของแบบฟอร์มนี้ว่าตรวจ 5 รายการ คือ '
    || 'อุณหภูมิแกนกลางวัตถุดิบ RM (0–7 °C) · ขนาดของวัตถุดิบ ใบมีดใหญ่ (ø 24.5–25.0 mm) · '
    || 'ขนาดของวัตถุดิบ ใบมีดเล็ก (ø 2.2–2.5 mm) · ลักษณะปรากฏ (เนื้อสัมผัสเนียนละเอียด ปกติ) · '
    || 'อุณหภูมิห้องผลิต (≤ 18.0 °C) '
    || 'และหน่วยของใบบันทึกคือรอบการลดขนาดของกะนั้น ครอบคลุมวัตถุดิบทุกตัวที่ผ่านเครื่องในรอบเดียวกัน '
    || 'ไม่ใช่หนึ่งใบต่อหนึ่งวัตถุดิบ'),
  modified = strftime('%Y-%m-%dT%H:%M:%fZ','now')
WHERE docNo = 'FM-QA-04';

