-- Building the daily in-process summary meant reading every record on the
-- register, and one thing showed up that is worth writing down before the
-- surveillance audit: the 56 in-process records carry five different form
-- numbers between them.
--
--   FM-QA-05  22 ใบ  บันทึกการตรวจสอบระหว่างกระบวนการผลิต
--   FM-QA-28  18 ใบ  บันทึกการตรวจสอบเครื่องตรวจจับโลหะ
--   FM-QA-04   6 ใบ  บันทึกการตรวจสอบกระบวนการหมัก-ผสม
--   FM-QA-06   5 ใบ  บันทึกการตรวจสอบผลิตภัณฑ์ขั้นตอนการแพค/ซีล/จัดเก็บ
--   FM-QA-32   5 ใบ  บันทึกการตรวจรับวัตถุดิบประเภทเครื่องปรุง และวัตถุเจือปนอาหาร
--
-- This migration records the counts and does NOT change any record. Which
-- form a check was written on is QA's data, not mine to rewrite — and two of
-- the five (FM-QA-04, FM-QA-06) may well be the correct form for what was
-- actually inspected that day. The code default is fixed separately: new
-- records now open as FM-QA-05.

UPDATE haccp_documents SET
  notes = TRIM(COALESCE(notes,'') || ' | [17/08/26] บันทึกในระบบที่ใช้แบบฟอร์มนี้ 22 ใบ '
    || 'จากทั้งหมด 56 ใบบนทะเบียนตรวจระหว่างผลิต — อีก 34 ใบใช้เลขแบบฟอร์มอื่น '
    || '(FM-QA-28 18 ใบ · FM-QA-04 6 ใบ · FM-QA-06 5 ใบ · FM-QA-32 5 ใบ) รอ QA ยืนยันว่าตั้งใจหรือไม่'),
  modified = strftime('%Y-%m-%dT%H:%M:%fZ','now')
WHERE docNo = 'FM-QA-05';

