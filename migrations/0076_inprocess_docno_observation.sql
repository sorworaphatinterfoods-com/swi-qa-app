<b>ที่ค่อนข้างชัดว่าไม่ตรงคือ FM-QA-28 และ FM-QA-32</b> ซึ่งทะเบียนกำหนดไว้เป็นเครื่องตรวจจับโลหะและการตรวจรับเครื่องปรุง คนละเรื่องกับการตรวจระหว่างผลิต

