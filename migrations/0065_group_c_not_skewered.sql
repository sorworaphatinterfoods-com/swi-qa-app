-- QA confirmed on 15/08/26 that the nine กลุ่ม C products do not go through
-- skewering: the six หมูหอมซีเลคชั่น items, โครงไก่ (-0032), หมูพวง (-0033) and
-- ไก่นุ่มหมัก (-0026).
--
-- That answer does more than fill a column. Two consequences follow, and the
-- second one reaches product that is being made now.
--
--   Scope. QM-QA-04 ข้อ 1 defines its scope as "กลุ่มผลิตภัณฑ์เนื้อสัตว์หมัก
--   เสียบไม้แช่เยือกแข็ง". A product that is not skewered does not meet that
--   definition, so nine registered products sit outside the approved hazard
--   analysis by the document's own words.
--
--   CCP-01. The critical limits — Fe Ø1.0, Non-Fe Ø1.5, SUS Ø2.0 — were set
--   against a thin skewer passing through the aperture. A bag of bulk marinated
--   meat is thick, wet and salty, which is the combination that degrades metal
--   detector sensitivity; a chicken carcass adds bone. QM-QA-06 already requires
--   revalidation "เมื่อเปลี่ยนผลิตภัณฑ์", and going from a skewer to a block is
--   that change. Until the test piece has been run against these forms and the
--   achieved sensitivity recorded, nobody can say the CCP is in control for
--   them.

